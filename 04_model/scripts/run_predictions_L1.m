%% RUN_PREDICTIONS_L1  C01 frozen predictions + one-at-a-time sensitivity.
%
%  Runs longitudinal_L1.slx for two manoeuvres, at nominal parameters and at
%  the low/high end of every ASSUMED range in params/vehicle_params.m:
%    accel  full throttle from standstill on flat ground
%    coast  throttle released at 30 km/h, motor at zero current (no regen)
%
%  The point of the sweep is not the band itself: it is the RANKING. The
%  parameter that dominates a band is the first thing to measure.
%
%  Band method: one-at-a-time, |delta| per parameter combined by root-sum-
%  square, i.e. assumes the parameters are independent. Battery voltage is
%  a TEST CONDITION (measured before the run), not an unknown, so it is
%  reported separately and left out of the band.
%
%  History
%    v1 2026-10-08  coast-down 25 -> 10 km/h, rider mass ASSUMED 72 kg [65 80]
%    v2 2026-10-09  rider mass MEASURED (72 kg) -> out of the sweep.
%                   Coast-down 30 -> 5 km/h: Pol's call (C01 exam, G8) - start
%                   as high as the vehicle reliably reaches, so CdA shows more.
%                   Nominal parameters unchanged. No vehicle data used.
%
%  Outputs (04_model/results/):
%    C01_predictions_table.md   the table
%    C01_oat.csv                one-at-a-time metrics, for the deck figures
%    C01_accel_curves.csv       v(t), every case
%    C01_coast_curves.csv       v(t), every case
%    C01_envelope.csv           static wheel-force envelope vs speed
%    C01_coast_start.csv        how much CdA shows vs coast-down start speed

here = fileparts(mfilename('fullpath'));
root = fullfile(here, '..');
res = fullfile(root, 'results');
run(fullfile(root, 'params', 'motor_params.m'));
run(fullfile(root, 'params', 'throttle_params.m'));
run(fullfile(root, 'params', 'vehicle_params.m'));

mdl = 'longitudinal_L1';
if ~exist(fullfile(root, 'models', [mdl '.slx']), 'file')
    run(fullfile(here, 'build_longitudinal_L1.m'));
end
load_system(fullfile(root, 'models', [mdl '.slx']));

V_oc_nom   = 50.0;            % [V] ~3.85 V/cell, mid state of charge
V_oc_range = [46.0 54.0];     % [V] test condition, not an unknown
v_c0 = 30;  v_c1 = 5;         % [km/h] coast-down window

base = struct('veh', veh, 'bat', bat);

% name, struct, field  - every ASSUMED parameter with a range
sweep = {
    'r_roll',       'veh', 'r_roll'
    'Crr',          'veh', 'Crr'
    'CdA',          'veh', 'CdA'
    'eta_drive',    'veh', 'eta_drive'
    'mu',           'veh', 'mu'
    'x_cg',         'veh', 'x_cg'
    'm_rot_wheels', 'veh', 'm_rot_wheels'
    'R_int',        'bat', 'R_int'
    };

opt = struct('V_oc', V_oc_nom, 'v_c0', v_c0, 'v_c1', v_c1, 'ramp', true);
nom = run_case(mdl, base.veh, base.bat, mot, lim, thr, opt);

n = size(sweep, 1);
lo = repmat(nom, n, 1); hi = lo;
for k = 1:n
    [nm, st, fld] = sweep{k, :};
    rng = base.(st).([fld '_range']);
    for side = 1:2
        v = base.veh; bt = base.bat;
        if strcmp(st, 'veh'), v.(fld) = rng(side); else, bt.(fld) = rng(side); end
        r = run_case(mdl, v, bt, mot, lim, thr, opt);
        if side == 1, lo(k) = r; else, hi(k) = r; end
    end
    fprintf('%-13s done\n', nm);
end
o2 = opt; o2.V_oc = V_oc_range(1); vlo = run_case(mdl, base.veh, base.bat, mot, lim, thr, o2);
o2.V_oc = V_oc_range(2);           vhi = run_case(mdl, base.veh, base.bat, mot, lim, thr, o2);

%% Table
metrics = {'v_top_kmh', 't_0_25', 't_coast', 'v_batlim_kmh'};
labels  = {'Top speed [km/h]', 'Time 0-25 km/h [s]', ...
           sprintf('Coast-down %d-%d km/h [s]', v_c0, v_c1), ...
           'Speed where 40 A battery limit kicks in [km/h]'};
fid = fopen(fullfile(res, 'C01_predictions_table.md'), 'w', 'n', 'UTF-8');
fprintf(fid, '<!-- generated by scripts/run_predictions_L1.m on %s -->\n\n', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
fprintf(fid, 'Nominal at V_oc = %.1f V, m_total = %.0f kg.\n\n', V_oc_nom, base.veh.m_vehicle + base.veh.m_driver);
fprintf(fid, '| Prediction | Nominal | Band (RSS) | Dominant parameter | V_oc %.0f / %.0f V |\n|---|---|---|---|---|\n', V_oc_range);
for m = 1:numel(metrics)
    f = metrics{m};
    d = max(abs([[lo.(f)] - nom.(f); [hi.(f)] - nom.(f)]), [], 1);
    band = sqrt(sum(d.^2));
    [~, kmax] = max(d);
    fprintf(fid, '| %s | %.1f | +/- %.1f | %s (%.0f %% of variance) | %.1f / %.1f |\n', ...
        labels{m}, nom.(f), band, sweep{kmax, 1}, 100*d(kmax)^2/sum(d.^2), vlo.(f), vhi.(f));
end
fprintf(fid, '\n### One-at-a-time detail (low / high end of each range)\n\n');
fprintf(fid, '| Parameter | Range | Top speed | t 0-25 | Coast %d-%d |\n|---|---|---|---|---|\n', v_c0, v_c1);
for k = 1:n
    [nm, st, fld] = sweep{k, :};
    rng = base.(st).([fld '_range']);
    fprintf(fid, '| %s | %g - %g | %.1f / %.1f | %.2f / %.2f | %.1f / %.1f |\n', nm, rng, ...
        lo(k).v_top_kmh, hi(k).v_top_kmh, lo(k).t_0_25, hi(k).t_0_25, lo(k).t_coast, hi(k).t_coast);
end
fprintf(fid, '\nGrip-limited at launch (nominal): %s. Peak battery current (nominal): %.1f A.\n', ...
    mat2str(nom.grip_limited), nom.I_bat_peak);
fclose(fid);
type(fullfile(res, 'C01_predictions_table.md'));

%% CSV exports for the deck figures
names = sweep(:, 1)';
ta = (0:0.05:30)'; tc = (0:0.1:60)';
TA = table(ta, interp1(nom.t_acc, nom.v_acc, ta)*3.6, 'VariableNames', {'t', 'nominal'});
TC = table(tc, interp1(nom.t_cst, nom.v_cst, tc)*3.6, 'VariableNames', {'t', 'nominal'});
for k = 1:n
    TA.([names{k} '_lo']) = interp1(lo(k).t_acc, lo(k).v_acc, ta)*3.6;
    TA.([names{k} '_hi']) = interp1(hi(k).t_acc, hi(k).v_acc, ta)*3.6;
    TC.([names{k} '_lo']) = interp1(lo(k).t_cst, lo(k).v_cst, tc)*3.6;
    TC.([names{k} '_hi']) = interp1(hi(k).t_cst, hi(k).v_cst, tc)*3.6;
end
writetable(TA, fullfile(res, 'C01_accel_curves.csv'));
writetable(TC, fullfile(res, 'C01_coast_curves.csv'));
M = table(names', [lo.v_top_kmh]', [hi.v_top_kmh]', [lo.t_0_25]', [hi.t_0_25]', ...
    [lo.t_coast]', [hi.t_coast]', 'VariableNames', ...
    {'param', 'vtop_lo', 'vtop_hi', 't025_lo', 't025_hi', 'tcst_lo', 'tcst_hi'});
M = [M; {'NOMINAL', nom.v_top_kmh, nom.v_top_kmh, nom.t_0_25, nom.t_0_25, nom.t_coast, nom.t_coast}];
M = [M; {'V_oc', vlo.v_top_kmh, vhi.v_top_kmh, vlo.t_0_25, vhi.t_0_25, vlo.t_coast, vhi.t_coast}];
M = [M; {'V_BATLIM', nom.v_batlim_kmh, NaN, NaN, NaN, NaN, NaN}];
writetable(M, fullfile(res, 'C01_oat.csv'));

%% Static envelope: same model, throttle ramp removed and road load zeroed,
%% so the full-throttle run traces the maximum wheel force at every speed all
%% the way to the no-load speed. The road load is drawn separately: where the
%% two curves cross is the top speed.
o2 = opt; o2.ramp = false;
v0load = base.veh; v0load.Crr = 0; v0load.CdA = 0;
v0load.mu = Inf;   % motor capability, uncapped; grip is drawn as its own line
env = run_case(mdl, v0load, base.bat, mot, lim, thr, o2);
veh_n = base.veh; veh_n.m_total = veh_n.m_vehicle + veh_n.m_driver;
F_res = veh_n.Crr*veh_n.m_total*veh_n.g + 0.5*veh_n.rho_air*veh_n.CdA*env.v_acc.^2;
F_grip = veh_n.mu*veh_n.x_cg*veh_n.m_total*veh_n.g;
E = table(env.v_acc*3.6, env.F_acc, env.iq_acc, env.ib_acc, F_res, ...
    repmat(F_grip, numel(env.v_acc), 1), ...
    'VariableNames', {'v_kmh', 'F_wheel', 'iq', 'I_bat', 'F_road', 'F_grip'});
writetable(E, fullfile(res, 'C01_envelope.csv'));

%% Does a higher coast-down start make CdA visible? (Pol, exam G8)
starts = [15 20 25 30];
CS = zeros(numel(starts), 4);
kC = find(strcmp(names, 'CdA')); kR = find(strcmp(names, 'Crr'));
for j = 1:numel(starts)
    o2 = opt; o2.v_c0 = starts(j);
    t0 = run_coast(mdl, base.veh, base.bat, mot, lim, thr, o2);
    dC = zeros(1, 2); dR = zeros(1, 2);
    for side = 1:2
        v = base.veh; v.CdA = v.CdA_range(side);
        dC(side) = run_coast(mdl, v, base.bat, mot, lim, thr, o2) - t0;
        v = base.veh; v.Crr = v.Crr_range(side);
        dR(side) = run_coast(mdl, v, base.bat, mot, lim, thr, o2) - t0;
    end
    CS(j, :) = [starts(j), t0, max(abs(dC)), max(abs(dR))];
end
writetable(array2table(CS, 'VariableNames', {'v_start_kmh', 't_nom', 'dt_CdA', 'dt_Crr'}), ...
    fullfile(res, 'C01_coast_start.csv'));
disp(array2table(CS, 'VariableNames', {'v_start_kmh', 't_nom', 'dt_CdA', 'dt_Crr'}));

%% ------------------------------------------------------------------
function [in, veh] = prep(mdl, veh, bat, mot, lim, thr)
    veh.m_total = veh.m_vehicle + veh.m_driver;
    veh.m_eq = veh.m_total + veh.m_rot_wheels + mot.J * veh.i_gear^2 / veh.r_roll^2;
    P = struct('p', mot.p, 'lambda', mot.lambda_m, 'Rs', mot.Rs, 'Lq', mot.Lq, ...
        'duty_max', lim.duty_max, 'i_batt_max', lim.i_batt_max, ...
        'T_c', mot.T_coulomb, 'b', mot.b_visc);
    in = Simulink.SimulationInput(mdl);
    in = in.setVariable('veh', veh).setVariable('bat', bat).setVariable('mot', mot) ...
        .setVariable('lim', lim).setVariable('thr', thr).setVariable('P', P);
end

function t = run_coast(mdl, veh, bat, mot, lim, thr, opt)
    in = prep(mdl, veh, bat, mot, lim, thr);
    scn = struct('t_end', 120, 'v0', opt.v_c0/3.6, 'V_oc', opt.V_oc, ...
        'throttle', timeseries([0 0]', [0 120]'));
    o = sim(in.setVariable('scn', scn));
    v = o.yout{1}.Values;
    i1 = find(v.Data <= opt.v_c1/3.6, 1);
    if isempty(i1), t = NaN; else, t = v.Time(i1); end
end

function r = run_case(mdl, veh, bat, mot, lim, thr, opt)
    [in, veh] = prep(mdl, veh, bat, mot, lim, thr);
    if ~opt.ramp
        thr.ramp_time_pos = 1e-3;
        in = in.setVariable('thr', thr);
    end

    % Full-throttle acceleration (throttle opens at t = 0.5 s)
    scn = struct('t_end', 40, 'v0', 0, 'V_oc', opt.V_oc, ...
        'throttle', timeseries([0 0 1 1]', [0 0.5 0.5001 40]'));
    o = sim(in.setVariable('scn', scn));
    v = o.yout{1}.Values; ib = o.yout{2}.Values;
    fw = o.yout{4}.Values; iq = o.yout{5}.Values;
    r.t_acc = v.Time; r.v_acc = v.Data(:);
    r.F_acc = interp1(fw.Time, fw.Data(:), v.Time);
    r.iq_acc = interp1(iq.Time, iq.Data(:), v.Time);
    r.ib_acc = interp1(ib.Time, ib.Data(:), v.Time);
    r.v_top_kmh = 3.6 * v.Data(end);
    i25 = find(v.Data >= 25/3.6, 1);
    if isempty(i25), r.t_0_25 = NaN; else, r.t_0_25 = v.Time(i25) - 0.5; end
    r.I_bat_peak = max(ib.Data);
    ilim = find(r.ib_acc >= 0.99 * lim.i_batt_max, 1);
    if isempty(ilim), r.v_batlim_kmh = NaN; else, r.v_batlim_kmh = 3.6 * v.Data(ilim); end
    F_grip = veh.mu * veh.x_cg * veh.m_total * veh.g;
    r.grip_limited = any(abs(fw.Data - F_grip) < 1e-6);

    % Coast-down
    scn = struct('t_end', 120, 'v0', opt.v_c0/3.6, 'V_oc', opt.V_oc, ...
        'throttle', timeseries([0 0]', [0 120]'));
    o = sim(in.setVariable('scn', scn));
    v = o.yout{1}.Values;
    r.t_cst = v.Time; r.v_cst = v.Data(:);
    i1 = find(v.Data <= opt.v_c1/3.6, 1);
    if isempty(i1), r.t_coast = NaN; else, r.t_coast = v.Time(i1); end
end
